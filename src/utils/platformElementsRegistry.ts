/**
 * Finds target definition by exact id or fuzzy matching
 */
export function findPlatformTargetById(targetId: string): PlatformTargetDefinition | undefined {
  if (!targetId) return undefined;
  const clean = targetId.split('?')[0].trim().toLowerCase();
  return AVAILABLE_PLATFORM_TARGETS.find((p) => p.id.toLowerCase() === clean);
}

